"""
Install my global instructions for every coding agent on this computer.

They live once, as plain Markdown, in two folders next to this script:
  rules/                  how to work with me (pacing, one step at a time, ask before editing...)
  general_instructions/   how to talk to me (acronyms, yes-man protocol...)

Each agent reads its global instructions from a different place and in a different way,
so this script writes them where each one looks:

  Claude Code  ~/.claude/<folder>/<name>.md   a copy of every file, same folder names
               ~/.claude/CLAUDE.md            an index that loads them, one "@" line per file
  Codex        ~/.codex/AGENTS.md             everything in one file: Codex can't load
                                              other files from AGENTS.md

Nothing is lost: a file that already exists with different content is renamed to
"<name>.backup-<date-time>" before it's replaced, and files this script doesn't manage
(for example other rules you added by hand in ~/.claude/rules/) are left alone.

Run it with:
  python3 global/install.py                      (install for every agent)
  python3 global/install.py --dry-run            (show what would change, write nothing)
  python3 global/install.py --only codex         (one agent)
  python3 global/install.py --home /some/folder  (install into a test folder instead of ~)
"""

import argparse
import os
import sys
from datetime import datetime
from pathlib import Path

GLOBAL_DIR = Path(__file__).resolve().parent
# Installed in this order; each is a folder of .md files next to this script.
SOURCE_FOLDERS = ["rules", "general_instructions"]
REPO_NAME = "how_i_like_my_agents"

# Codex stops reading instructions after this many bytes (its project_doc_max_bytes
# default, 32 KiB), and the project's own AGENTS.md counts toward the same budget.
CODEX_MAX_BYTES = 32 * 1024
CODEX_WARN_SHARE = 0.5

GENERATED_NOTE = (
    f"<!-- Generated by {REPO_NAME}/global/install.py. Edit the files in that repo and\n"
    "     re-run the script; changes made here are overwritten. -->\n"
)

# Result of writing one file
CREATED = "created"
UPDATED = "updated"
UNCHANGED = "unchanged"


def load_sources():
    """(folder, name) -> text, for every .md file in each source folder (sorted by name)."""
    sources = {
        (folder, path.stem): path.read_text(encoding="utf-8")
        for folder in SOURCE_FOLDERS
        for path in sorted((GLOBAL_DIR / folder).glob("*.md"))
        if not path.name.startswith(".")
    }
    if not sources:
        sys.exit(f"No instructions found in {', '.join(SOURCE_FOLDERS)} under {GLOBAL_DIR}")
    return sources


def write_file(path, text, dry_run):
    """Write text to path, backing up a different existing file first.

    Returns (result, backup_path or None).
    """
    if path.exists():
        if path.read_text(encoding="utf-8") == text:
            return UNCHANGED, None
        backup = path.with_name(f"{path.name}.backup-{datetime.now():%Y%m%d-%H%M%S}")
        if not dry_run:
            path.rename(backup)
            path.write_text(text, encoding="utf-8")
        return UPDATED, backup
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return CREATED, None


def claude_files(sources, home):
    """Path -> text for Claude Code: one file per instruction plus the CLAUDE.md index."""
    claude_dir = home / ".claude"
    files = {claude_dir / folder / f"{name}.md": text for (folder, name), text in sources.items()}
    # "@~/..." is how CLAUDE.md loads another file. It always means the real home
    # folder, which is where Claude Code looks, even when --home points elsewhere.
    sections = []
    for folder in SOURCE_FOLDERS:
        names = [name for (f, name) in sources if f == folder]
        if names:
            sections.append(f"## {folder}\n\n" + "\n".join(f"@~/.claude/{folder}/{name}.md" for name in names))
    files[claude_dir / "CLAUDE.md"] = (
        "# How I like to work (all projects)\n\n"
        + GENERATED_NOTE
        + f"\nEach instruction lives in its own file under ~/.claude/ ({', '.join(SOURCE_FOLDERS)}).\n\n"
        + "\n\n".join(sections)
        + "\n"
    )
    return files


def codex_files(sources, home, use_env):
    """Path -> text for Codex: every instruction in one AGENTS.md."""
    codex_home = Path(os.environ["CODEX_HOME"]) if use_env and os.environ.get("CODEX_HOME") else home / ".codex"
    body = "\n\n".join(text.strip() for text in sources.values())
    text = "# How I like to work (all projects)\n\n" + GENERATED_NOTE + "\n" + body + "\n"
    return {codex_home / "AGENTS.md": text}


def parse_args():
    parser = argparse.ArgumentParser(description="Install my global instructions for each coding agent.")
    parser.add_argument("--only", choices=["claude", "codex"], help="install for one agent only")
    parser.add_argument("--dry-run", action="store_true", help="show what would change, write nothing")
    parser.add_argument("--home", help="install into this folder instead of your home folder (for testing)")
    return parser.parse_args()


def main():
    args = parse_args()
    home = Path(args.home).expanduser().resolve() if args.home else Path.home()
    sources = load_sources()

    targets = {}
    if args.only in (None, "claude"):
        targets["Claude Code"] = claude_files(sources, home)
    if args.only in (None, "codex"):
        # CODEX_HOME moves Codex's folder, but a test install (--home) must never
        # write outside the test folder.
        targets["Codex"] = codex_files(sources, home, use_env=args.home is None)

    print(f"{'Dry run: nothing is written. ' if args.dry_run else ''}"
          f"Installing {len(sources)} files from {', '.join(SOURCE_FOLDERS)} in {GLOBAL_DIR}\n")
    backups = []
    for agent, files in targets.items():
        print(f"{agent}:")
        for path, text in files.items():
            result, backup = write_file(path, text, args.dry_run)
            print(f"  {result:9}  {path}")
            if backup:
                backups.append(backup)
                print(f"             old version {'would be ' if args.dry_run else ''}saved as {backup.name}")
        print()

    for path, text in targets.get("Codex", {}).items():
        size = len(text.encode("utf-8"))
        if size > CODEX_MAX_BYTES * CODEX_WARN_SHARE:
            print(f"Warning: {path.name} is {size:,} bytes, over half of Codex's {CODEX_MAX_BYTES:,}-byte "
                  "limit for all instructions combined. A project's own AGENTS.md may get cut off.\n")

    if backups:
        print("Check the backups above: if they had instructions you want to keep, add them to")
        print(f"one of the folders in {GLOBAL_DIR} and run this again. Then delete the backups.\n")
    print("Done. Start a new session in each agent for the instructions to take effect.")


if __name__ == "__main__":
    main()
