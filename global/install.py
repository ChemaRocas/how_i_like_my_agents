"""
Install my global instructions for every coding agent on this computer.

They live once, as plain Markdown, in folders next to this script:
  rules/                  how to work with me (pacing, one step at a time, ask before editing...)
  general_instructions/   how to talk to me (acronyms, yes-man protocol...)
  skills/<name>/SKILL.md  procedures an agent loads when their description says to

Each agent reads its global instructions from a different place and in a different way,
so this script writes them where each one looks:

  Claude Code  ~/.claude/how_i_like_my_agents/<folder>/<name>.md   a copy of every file
               ~/.claude/CLAUDE.md            an index that loads them, one "@" line per file
               ~/.claude/skills/<name>/       each skill
  Codex        ~/.codex/AGENTS.md             everything in one file: Codex can't load
                                              other files from AGENTS.md
               ~/.agents/skills/<name>/       each skill (Codex's personal skills folder)

Skills this script installed carry a marker file (.installed-by-how_i_like_my_agents). A
marked skill that no longer exists in this repo is retired: moved to a backup folder no
agent loads skills from. Skills without the marker are someone else's and are left alone.

Claude's copies go in a folder of their own, loaded only through the "@" lines, and NOT in
~/.claude/rules/: Claude Code can load every file in that folder by itself, so a copy there
would load twice, and an old one would stay active after it's removed from this repo.

This script owns ~/.claude/how_i_like_my_agents/: a file there that no longer exists in
this repo is retired (renamed to a backup), so Claude and Codex always get the same set.
Copies an earlier manual setup left in ~/.claude/rules/ under the same names are retired
the same way. Anything else in ~/.claude/rules/ is yours: it stays, and stays active in
Claude Code, but it isn't part of this repo and Codex never sees it.

Nothing is lost: every replaced or retired file is first renamed to
"<name>.backup-<date-time>".

Run it with:
  python3 global/install.py                      (install for every agent)
  python3 global/install.py --dry-run            (show what would change, write nothing)
  python3 global/install.py --only codex         (one agent)
  python3 global/install.py --home /some/folder  (install into a test folder instead of ~)
"""

import argparse
import os
import sys
from datetime import datetime
from pathlib import Path

GLOBAL_DIR = Path(__file__).resolve().parent
# Installed in this order; each is a folder of .md files next to this script.
SOURCE_FOLDERS = ["rules", "general_instructions"]
REPO_NAME = "how_i_like_my_agents"

# Codex stops reading instructions after this many bytes (its project_doc_max_bytes
# default, 32 KiB), and the project's own AGENTS.md counts toward the same budget.
CODEX_MAX_BYTES = 32 * 1024
CODEX_WARN_SHARE = 0.5

GENERATED_NOTE = (
    f"<!-- Generated by {REPO_NAME}/global/install.py. Edit the files in that repo and\n"
    "     re-run the script; changes made here are overwritten, except below the\n"
    "     'local' line at the end. -->\n"
)

# Codex gets one file, so it needs a part the installer never overwrites: everything after
# this line is kept on every install. Claude's equivalent is ~/.claude/rules/.
CODEX_LOCAL_MARKER = "<!-- local: kept by install.py -->"
CODEX_LOCAL_HINT = (
    "<!-- Instructions for this computer only (for example, ones an employer requires) go\n"
    "     below. They are never overwritten and never go into the repo. -->\n"
)

# Claude's copies live here, under ~/.claude/, in a folder this script owns.
CLAUDE_MANAGED_FOLDER = REPO_NAME
# Claude Code can load this folder automatically; nothing of ours may live in it.
CLAUDE_AUTOLOAD_FOLDER = "rules"

# Skills: one folder each under global/skills/, installed into each agent's skills folder.
SKILLS_FOLDER = "skills"
SKILL_MARKER = f".installed-by-{REPO_NAME}"
SKILL_MARKER_TEXT = (
    f"Installed by {REPO_NAME}/global/install.py. Edit the skill in that repo and re-run\n"
    "the script; changes made here are overwritten.\n"
)

# Result of writing one file
CREATED = "created"
UPDATED = "updated"
UNCHANGED = "unchanged"
RETIRED = "retired"


def load_sources():
    """(folder, name) -> text, for every .md file in each source folder (sorted by name)."""
    sources = {
        (folder, path.stem): path.read_text(encoding="utf-8")
        for folder in SOURCE_FOLDERS
        for path in sorted((GLOBAL_DIR / folder).glob("*.md"))
        if not path.name.startswith(".")
    }
    if not sources:
        sys.exit(f"No instructions found in {', '.join(SOURCE_FOLDERS)} under {GLOBAL_DIR}")
    return sources


def backup_path(path):
    """Where a replaced or retired file is kept. Not ending in .md, so no agent loads it."""
    return path.with_name(f"{path.name}.backup-{datetime.now():%Y%m%d-%H%M%S}")


def write_file(path, text, dry_run):
    """Write text to path, backing up a different existing file first.

    Returns (result, backup_path or None).
    """
    if path.exists():
        if path.read_text(encoding="utf-8") == text:
            return UNCHANGED, None
        backup = backup_path(path)
        if not dry_run:
            path.rename(backup)
            path.write_text(text, encoding="utf-8")
        return UPDATED, backup
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return CREATED, None


def claude_files(sources, home):
    """Path -> text for Claude Code: one file per instruction plus the CLAUDE.md index."""
    claude_dir = home / ".claude"
    managed = claude_dir / CLAUDE_MANAGED_FOLDER
    files = {managed / folder / f"{name}.md": text for (folder, name), text in sources.items()}
    # "@~/..." is how CLAUDE.md loads another file. It always means the real home
    # folder, which is where Claude Code looks, even when --home points elsewhere.
    sections = []
    for folder in SOURCE_FOLDERS:
        names = [name for (f, name) in sources if f == folder]
        if names:
            sections.append(f"## {folder}\n\n" + "\n".join(
                f"@~/.claude/{CLAUDE_MANAGED_FOLDER}/{folder}/{name}.md" for name in names))
    files[claude_dir / "CLAUDE.md"] = (
        "# How I like to work (all projects)\n\n"
        + GENERATED_NOTE
        + f"\nEach instruction lives in its own file under ~/.claude/{CLAUDE_MANAGED_FOLDER}/.\n\n"
        + "\n\n".join(sections)
        + "\n"
    )
    return files


def claude_files_to_retire(sources, home, installing):
    """Existing Claude files that would make Claude and Codex disagree, so must be retired.

    - In the managed folder: any .md that isn't one of the files being installed (an
      instruction renamed or deleted in this repo).
    - In ~/.claude/rules/: a copy with the same name as one of ours, left by an earlier
      manual setup. Claude Code can load that folder by itself, so it would load twice.
    """
    claude_dir = home / ".claude"
    stale = []
    managed = claude_dir / CLAUDE_MANAGED_FOLDER
    if managed.is_dir():
        stale += [path for path in sorted(managed.rglob("*.md")) if path not in installing]
    autoload = claude_dir / CLAUDE_AUTOLOAD_FOLDER
    our_names = {f"{name}.md" for (_, name) in sources}
    if autoload.is_dir():
        stale += [path for path in sorted(autoload.glob("*.md")) if path.name in our_names]
    return stale


def heading(text):
    """The first "# " heading of a Markdown text (used to order Codex's file: Rule A before B)."""
    return next((line[2:].strip() for line in text.splitlines() if line.startswith("# ")), "")


def codex_files(sources, home, use_env):
    """Path -> text for Codex: every instruction in one AGENTS.md, plus the local section.

    Everything below CODEX_LOCAL_MARKER in the existing file is kept as it is: that's where
    instructions for this computer only (an employer's, say) live, outside this repo.
    """
    codex_home = Path(os.environ["CODEX_HOME"]) if use_env and os.environ.get("CODEX_HOME") else home / ".codex"
    path = codex_home / "AGENTS.md"
    body = "\n\n".join(text.strip() for text in sorted(sources.values(), key=heading))
    local = ""
    if path.is_file():
        existing = path.read_text(encoding="utf-8")
        if CODEX_LOCAL_MARKER in existing:
            local = existing.split(CODEX_LOCAL_MARKER, 1)[1]
    if not local.strip():
        local = "\n" + CODEX_LOCAL_HINT
    text = ("# How I like to work (all projects)\n\n" + GENERATED_NOTE + "\n" + body + "\n\n"
            + CODEX_LOCAL_MARKER + local)
    return {path: text}


def load_skills():
    """Skill name -> {path inside the skill folder: text}, for every folder in global/skills/
    that has a SKILL.md. Every file in the folder goes with it (scripts, references)."""
    skills = {}
    for folder in sorted((GLOBAL_DIR / SKILLS_FOLDER).glob("*/SKILL.md")):
        skill_dir = folder.parent
        skills[skill_dir.name] = {
            path.relative_to(skill_dir): path.read_text(encoding="utf-8")
            for path in sorted(skill_dir.rglob("*"))
            if path.is_file() and not path.name.startswith(".")
        }
    return skills


def skill_files(skills, skills_root):
    """Path -> text for one agent's skills folder, each skill with its ownership marker."""
    files = {}
    for name, contents in skills.items():
        for relative, text in contents.items():
            files[skills_root / name / relative] = text
        files[skills_root / name / SKILL_MARKER] = SKILL_MARKER_TEXT
    return files


def skills_to_retire(skills, skills_root, retired_root):
    """(skill folder, where it goes) for each skill we installed earlier that's gone from
    this repo. The destination is outside every skills folder, so no agent loads it."""
    if not skills_root.is_dir():
        return []
    stamp = f"{datetime.now():%Y%m%d-%H%M%S}"
    return [
        (folder, retired_root / f"{folder.name}.backup-{stamp}")
        for folder in sorted(skills_root.iterdir())
        if (folder / SKILL_MARKER).is_file() and folder.name not in skills
    ]


def parse_args():
    parser = argparse.ArgumentParser(description="Install my global instructions for each coding agent.")
    parser.add_argument("--only", choices=["claude", "codex"], help="install for one agent only")
    parser.add_argument("--dry-run", action="store_true", help="show what would change, write nothing")
    parser.add_argument("--home", help="install into this folder instead of your home folder (for testing)")
    return parser.parse_args()


def main():
    args = parse_args()
    home = Path(args.home).expanduser().resolve() if args.home else Path.home()
    sources = load_sources()
    skills = load_skills()

    targets = {}
    to_retire = {}  # agent -> [(path, where it goes)]
    if args.only in (None, "claude"):
        files = claude_files(sources, home)
        to_retire["Claude Code"] = [
            (path, backup_path(path)) for path in claude_files_to_retire(sources, home, files)
        ] + skills_to_retire(skills, home / ".claude" / SKILLS_FOLDER,
                             home / ".claude" / CLAUDE_MANAGED_FOLDER / "retired-skills")
        files.update(skill_files(skills, home / ".claude" / SKILLS_FOLDER))
        targets["Claude Code"] = files
    if args.only in (None, "codex"):
        # CODEX_HOME moves Codex's folder, but a test install (--home) must never
        # write outside the test folder.
        files = codex_files(sources, home, use_env=args.home is None)
        # Codex's personal skills live in ~/.agents/skills/, not in its own folder.
        to_retire["Codex"] = skills_to_retire(skills, home / ".agents" / SKILLS_FOLDER,
                                              home / ".agents" / f"{REPO_NAME}-retired-skills")
        files.update(skill_files(skills, home / ".agents" / SKILLS_FOLDER))
        targets["Codex"] = files

    print(f"{'Dry run: nothing is written. ' if args.dry_run else ''}"
          f"Installing {len(sources)} instructions and {len(skills)} "
          f"skill{'' if len(skills) == 1 else 's'} from {GLOBAL_DIR}\n")
    backups = []
    for agent, files in targets.items():
        print(f"{agent}:")
        for path, text in files.items():
            result, backup = write_file(path, text, args.dry_run)
            print(f"  {result:9}  {path}")
            if backup:
                backups.append(backup)
                print(f"             old version {'would be ' if args.dry_run else ''}saved as {backup.name}")
        for path, destination in to_retire.get(agent, []):
            if not args.dry_run:
                destination.parent.mkdir(parents=True, exist_ok=True)
                path.rename(destination)
            backups.append(destination)
            print(f"  {RETIRED:9}  {path}")
            print(f"             no longer active; {'would be ' if args.dry_run else ''}kept as {destination}")
        print()

    for path, text in targets.get("Codex", {}).items():
        if path.name != "AGENTS.md":
            continue
        size = len(text.encode("utf-8"))
        if size > CODEX_MAX_BYTES * CODEX_WARN_SHARE:
            print(f"Warning: {path.name} is {size:,} bytes, over half of Codex's {CODEX_MAX_BYTES:,}-byte "
                  "limit for all instructions combined. A project's own AGENTS.md may get cut off.\n")

    if backups:
        print("Check the backups above. Instructions worth keeping go back in one of two places:")
        print(f"  - general ones: a folder in {GLOBAL_DIR}, then run this again;")
        print("  - ones for this computer only (an employer's, say): ~/.claude/rules/ for Claude,")
        print(f"    and below the '{CODEX_LOCAL_MARKER}' line in Codex's AGENTS.md.")
        print("Then delete the backups.\n")
    print("Done. Start a new session in each agent for the instructions to take effect.")


if __name__ == "__main__":
    main()
